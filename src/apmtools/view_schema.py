"""Versioned, non-mutating validation and explicit migration for saved views.

Stage 3A deliberately keeps schema v1 as the persistence format.  Diagnostic
checks are opt-in and never silently remove unknown/older settings.
"""
from __future__ import annotations

import copy
from dataclasses import dataclass
from typing import Any

CURRENT_SCHEMA_VERSION = 1


@dataclass(frozen=True)
class ViewIssue:
    view_id: str
    path: str
    severity: str
    message: str


def _is_sequence_of_strings(value: Any) -> bool:
    return isinstance(value, list) and all(isinstance(x, str) for x in value)


def validate_saved_views(views):
    """Structural validation; return a defensive copy preserving unknown fields.

    A legacy table may contain an embedded ``frame``; reads ignore it and an
    explicit migration strips it. This validator does not mutate source data.
    """
    if views is None:
        return []
    if not isinstance(views, list):
        raise TypeError('Summary.views must be a list or None')
    seen = set()
    for index, item in enumerate(views):
        if not isinstance(item, dict):
            raise ValueError(f'Saved view {index} must be a dictionary')
        if item.get('schema_version') != CURRENT_SCHEMA_VERSION or item.get('type') not in ('plot', 'table'):
            raise ValueError(f'Unsupported saved view configuration at index {index}')
        if not isinstance(item.get('settings'), dict):
            raise ValueError(f'Saved view settings must be a dictionary at index {index}')
        identifier = item.get('id')
        if not isinstance(identifier, str) or not identifier or identifier in seen:
            raise ValueError('Saved view IDs must be unique nonempty strings')
        seen.add(identifier)
    return copy.deepcopy(views)


def migrate_saved_views(views):
    """Explicit, idempotent v1 normalization (never mutates its argument).

    Removes only deprecated table DataFrame snapshots. Unknown fields remain
    intact to preserve compatibility. Unsupported schema versions raise.
    """
    result = validate_saved_views(views)
    for view in result:
        if view['type'] == 'table':
            view.pop('frame', None)
    return result


def inspect_saved_views(views, columns=None):
    """Report non-fatal configuration problems without modifying any view.

    ``columns`` can be an iterable of names from the owning Summary. Unknown
    settings are allowed. A reference may be virtual (``variables_x/Y``) or
    generated by earlier source steps, so only direct plot fields and initial
    source-step filters are checked against raw Summary columns.
    """
    result = validate_saved_views(views)
    available = None if columns is None else set(columns)
    issues = []
    for view in result:
        identifier = view['id']
        settings = view['settings']
        if not str(view.get('name', '')).strip():
            issues.append(ViewIssue(identifier, 'name', 'warning', 'View name is empty'))
        if view['type'] == 'table' and 'frame' in view:
            issues.append(ViewIssue(identifier, 'frame', 'warning', 'Legacy embedded table snapshot is ignored; migrate to remove it'))
        if view['type'] == 'plot':
            selected = settings.get('y', [])
            if selected is not None and not _is_sequence_of_strings(selected):
                issues.append(ViewIssue(identifier, 'settings.y', 'error', 'Expected a list of Y column names'))
            if available is not None:
                for field in ('x', 'y', 'group_by'):
                    values = settings.get(field, [])
                    if isinstance(values, str):
                        values = [values]
                    if not isinstance(values, (list, tuple)):
                        continue
                    for value in values:
                        if not isinstance(value, str):
                            continue
                        if value.startswith('variables_'):
                            continue
                        if value not in available:
                            issues.append(ViewIssue(identifier, f'settings.{field}', 'warning', f'Column not found: {value}'))
        chain = settings.get('source_steps', []) if view['type'] == 'table' else []
        if not isinstance(chain, list):
            issues.append(ViewIssue(identifier, 'settings.source_steps', 'error', 'Expected a list of transformation steps'))
        elif any(not isinstance(step, dict) for step in chain):
            issues.append(ViewIssue(identifier, 'settings.source_steps', 'error', 'Every transformation step must be a dictionary'))
    return issues
